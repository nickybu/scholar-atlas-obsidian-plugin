#!/usr/bin/env python3
"""Generate src/vocab.ts from neuro-labs-explorer's pipeline/vocab.py.

    python3 scripts/generate-vocab.py /path/to/neuro-labs-explorer

The vocabulary tags research methods and model systems from paper titles,
abstracts and MeSH terms. Its patterns use regex lookbehind, which some iOS
versions can't run (and Obsidian's review rules reject), so they're rewritten:

* the word fence ``(?<![a-z0-9])`` becomes ``(?:^|[^a-z0-9])``;
* an alternative guarded by ``(?<!x)`` loses the guard, and the tag gets an
  ``unless`` pattern: text matching it is blanked out before that tag is
  tested, so "guinea pig" can't count as "pig".
"""
import json
import re
import sys
from pathlib import Path

LOOKBEHIND = re.compile(r"\(\?<!([^()]*)\)")


def convert(pattern: str) -> tuple[str, list[str]]:
    """Strip leading lookbehind guards; return the pattern and the phrases they excluded."""
    guards = []
    while (m := LOOKBEHIND.match(pattern)):
        guards.append(m.group(1))
        pattern = pattern[m.end():]
    if "(?<" in pattern:
        sys.exit(f"Unsupported lookbehind inside a pattern: {pattern!r}")
    return pattern, [re.escape(g) if not set(g) & set("[]()?*+|\\") else g for g in guards]


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    explorer = Path(sys.argv[1]).expanduser()
    sys.path.insert(0, str(explorer / "pipeline"))
    import vocab  # noqa: E402

    tags = []
    for group, table in vocab.GROUPS.items():
        for tid, (label, category, pats, mesh) in table.items():
            alternatives, unless = [], []
            for p in pats:
                body, guards = convert(p)
                alternatives.append(body)
                # "(?<!guinea )pigs?" -> blank out "guinea pigs?" before testing this tag.
                unless += [g + body for g in guards]
            tags.append({
                "id": tid,
                "label": label,
                "category": category,
                "group": "modelSystems" if group == "organisms" else "methods",
                "pattern": "(?:^|[^a-z0-9])(?:" + "|".join(alternatives) + ")(?![a-z0-9])" if alternatives else "",
                "unless": "|".join(unless),
                "mesh": list(mesh),
            })

    out = Path(__file__).resolve().parent.parent / "src" / "vocab.ts"
    out.write_text(
        "/*\n"
        " * Generated by scripts/generate-vocab.py from neuro-labs-explorer's\n"
        f" * pipeline/vocab.py (version {vocab.VOCAB_VERSION}). Don't edit by hand.\n"
        " */\n\n"
        "export interface VocabTag {\n"
        "\tid: string;\n\tlabel: string;\n\tcategory: string;\n"
        "\tgroup: 'methods' | 'modelSystems';\n"
        "\t/** Matched against lowercased, normalised title + abstract. */\n\tpattern: string;\n"
        "\t/** Text matching this is blanked out before `pattern` is tested. */\n\tunless: string;\n"
        "\t/** MeSH descriptor names that also count as a match. */\n\tmesh: string[];\n"
        "}\n\n"
        f"export const VOCAB_VERSION = {json.dumps(vocab.VOCAB_VERSION)};\n\n"
        f"export const VOCAB: VocabTag[] = {json.dumps(tags, indent=1, ensure_ascii=False)};\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(tags)} tags to {out}")


if __name__ == "__main__":
    main()
