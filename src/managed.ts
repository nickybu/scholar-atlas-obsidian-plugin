/**
 * Sections of a note the plugin writes (between markers), without ever losing
 * what you write. Each section ends with a hidden signature: a short
 * fingerprint of every line the plugin wrote. When the section is rewritten:
 *
 * - lines still matching a fingerprint are the plugin's, and are replaced;
 * - lines that don't (ones you added, or plugin lines you edited) are moved
 *   out, just below the section, and kept;
 * - sections from earlier versions have no signature: every line that isn't
 *   exactly in the plugin's own format is moved out and kept.
 *
 * A section the plugin keeps as it is isn't touched (or re-signed), so your
 * edits in it are never mistaken for the plugin's. Pure functions, no
 * Obsidian imports.
 */

/** A hidden Obsidian comment: `%%sa:<fingerprint> <fingerprint>…%%`. */
const SIGNATURE = /^%%sa:([0-9a-z ]*)%%$/;

/** FNV-1a, as a short base-36 string: enough to tell a line from an edited one. */
export function lineHash(line: string): string {
	let h = 0x811c9dc5;
	for (let i = 0; i < line.length; i++) {
		h ^= line.charCodeAt(i);
		h = Math.imul(h, 0x01000193) >>> 0;
	}
	return h.toString(36).padStart(7, '0').slice(-6);
}

/** Section content with its signature appended: a fingerprint for each of its non-blank lines. */
export function sign(content: string): string {
	const body = content.endsWith('\n') || !content ? content : `${content}\n`;
	const prints = body.split('\n').filter((l) => l.trim()).map(lineHash);
	return `${body}%%sa:${[...new Set(prints)].join(' ')}%%\n`;
}

/** Lines exactly as the plugin writes them in its sections; anything else is yours. */
const GENERATED: RegExp[] = [
	/^\s*$/,
	SIGNATURE,
	// Papers
	/^\*From \[(?:OpenAlex|ORCID)\]\([^)\s]+\)(?: · \d+ works in total)?\*$/,
	/^- (?:n\.d\.|\d{4}(?:-\d{2}){0,2}) · \[(?:[^\]\\]|\\.)*\]\([^)\s]+\)(?: · \*(?:[^*\\]|\\.)*\*)?$/,
	/^_No papers found yet\._$/,
	/^_Not on OpenAlex or ORCID\. Add papers by hand outside these markers\._$/,
	/^_OpenAlex has no author `A\d+`\. Check the `openalex` property\._$/,
	/^> \[!question\] Which OpenAlex author is this\?$/,
	// Earlier versions: the Python script, then the plugin when it was called "Scientist network".
	/^> Paste the right ID into the `openalex` property, then (?:run \*(?:Scholar Atlas|Scientist network): Update this person\*|rerun the script)\.$/,
	/^> If none of these is them, write `none` there instead\.$/,
	/^> No matches found by name\. Add an `orcid` or `openalex` ID by hand\.$/,
	/^> - `A\d+` · \[(?:[^\]\\]|\\.)*\]\(https:\/\/openalex\.org\/A\d+\)(?: · ORCID [\dX-]+)?(?: · [^\n]*)? · \d+ works$/,
	// Collaborators
	/^\*From their latest \d+ papers?\*$/,
	/^\*\*(?:Co-authors|Companies|Institutions|Countries)\*\*$/,
	/^- \[\[[^\]]+\]\] · \d+ papers? %%[A-Za-z0-9]+%%$/,
	/^_No co-authors found on their latest papers\._$/,
	// Card, and the photo block it replaced
	/^```scholar-atlas$/,
	/^```$/,
	/^!\[\[[^\]|]+\|\d+\]\]$/,
	/^!\[photo\|\d+\]\([^)\s]+\)$/,
	// Research feed
	/^Papers from the last \d+ days by people in the network\. Generated by (?:the (?:Scholar Atlas|Scientist network) plugin|`tools\/update_papers\.py`); edits here are overwritten\.$/,
	/^# Research feed$/,
	/^Papers from the last \d+ days by people in the network\. Updated by the Scholar Atlas plugin; anything you add above or below this list is kept\.$/,
	/^- \d{4}(?:-\d{2}){0,2} · (?:\[\[[^\]]+\]\](?:, )?)+ · .+$/,
	/^_Nothing new in this window\._$/,
];

export function isGeneratedLine(line: string): boolean {
	return GENERATED.some((rx) => rx.test(line));
}

/** A section's content without its signature line. */
export function unsigned(section: string): string {
	return section.replace(/(^|\n)%%sa:[0-9a-z ]*%%\n?$/, '$1');
}

/** Lines of an existing section that you wrote (added, or edited from the plugin's), to keep when it's replaced. */
export function userLines(existing: string): string[] {
	const lines = existing.replace(/\n$/, '').split('\n');
	const sig = lines[lines.length - 1]?.match(SIGNATURE)?.[1];
	if (sig === undefined) return lines.filter((l) => !isGeneratedLine(l)); // from an earlier version
	const plugins = new Set(sig.split(' ').filter(Boolean));
	return lines.slice(0, -1).filter((l) => l.trim() && !plugins.has(lineHash(l)));
}

/** Put kept lines straight after the section's end marker, outside the section. */
export function keepAfter(text: string, end: string, kept: string[]): string {
	if (!kept.length) return text;
	const j = text.indexOf(end);
	if (j === -1) return `${text.replace(/\n*$/, '')}\n\n${kept.join('\n')}\n`;
	let after = j + end.length;
	if (text[after] === '\n') after++;
	return `${text.slice(0, after)}${kept.join('\n')}\n${text.slice(after)}`;
}
