import { test } from 'node:test';
import assert from 'node:assert/strict';
import { isGeneratedLine, sign, userLines } from '../src/managed.ts';
import { getSection, setSection } from '../src/papers.ts';
import { setTopBlock } from '../src/photo.ts';

const S = '<!-- s:start -->';
const E = '<!-- s:end -->';
const note = (inside: string) => `## Notes\nmine\n\n## Papers\n${S}\n${inside}${E}\n`;
const paper = (t: string) => `- 2026-01-01 · [${t}](https://doi.org/x) · *J*`;

test('an untouched section is simply replaced', () => {
	const before = note(sign(`${paper('Old')}\n`));
	assert.equal(setSection(before, S, E, 'Papers', `${paper('New')}\n`), note(sign(`${paper('New')}\n`)));
});

test('a section that has not changed is left exactly as it is, even if you edited it', () => {
	const edited = note(`${paper('Old')}\nMy thoughts on this paper\n${sign(`${paper('Old')}\n`).split('\n').at(-2)}\n`);
	const block = getSection(edited, S, E) ?? '';
	assert.equal(setSection(edited, S, E, 'Papers', block), edited);
});

test('lines you add inside a section are kept, just below it', () => {
	const edited = note(`${paper('Old')}\nMy thoughts on this paper\n${sign(`${paper('Old')}\n`).split('\n').at(-2)}\n`);
	const after = setSection(edited, S, E, 'Papers', `${paper('New')}\n`);
	assert.ok(after.includes(`${E}\nMy thoughts on this paper\n`));
	assert.ok(after.includes(paper('New')));
	assert.ok(after.startsWith('## Notes\nmine\n'));
});

test('a plugin line you edited is kept, and the unchanged ones are replaced', () => {
	const sig = sign(`${paper('Original title')}\n${paper('Untouched')}\n`).split('\n').at(-2);
	const edited = note(`${paper('Title I corrected')}\n${paper('Untouched')}\n${sig}\n`);
	const after = setSection(edited, S, E, 'Papers', `${paper('Brand new')}\n`);
	assert.ok(after.includes(`${E}\n${paper('Title I corrected')}\n`));
	assert.ok(!after.includes(paper('Untouched')));
});

test('sections from earlier versions (unsigned) keep only what is not in the plugin format', () => {
	const old = note(`*From [OpenAlex](https://openalex.org/A1) · 2 works in total*\n\n${paper('Old')}\nA note I wrote\n`);
	const after = setSection(old, S, E, 'Papers', `${paper('New')}\n`);
	assert.ok(after.includes(`${E}\nA note I wrote\n`));
	assert.ok(!after.includes(paper('Old')));
	assert.deepEqual(userLines(`${paper('x')}\n`), []);
});

test('removing a top block keeps what you wrote in it', () => {
	const text = `---\na: 1\n---\n<!-- p:start -->\n![[x.jpg|200]]\nNice photo\n<!-- p:end -->\n## Notes\n`;
	assert.equal(setTopBlock(text, '<!-- p:start -->', '<!-- p:end -->', null), '---\na: 1\n---\nNice photo\n## Notes\n');
});

test('the plugin format is recognised exactly', () => {
	assert.ok(isGeneratedLine(paper('A title')));
	assert.ok(isGeneratedLine('- [[People/Pia Leader|Pia Leader]] · 2 papers %%A300%%'));
	assert.ok(!isGeneratedLine(`${paper('A title')} great read!`));
	assert.ok(!isGeneratedLine('- [[Pia Leader]] my supervisor'));
});

test('lines written by earlier versions are recognised as the plugin\'s', () => {
	for (const line of [
		'> Paste the right ID into the `openalex` property, then run *Scientist network: Update this person*.',
		'> Paste the right ID into the `openalex` property, then rerun the script.',
		'Papers from the last 90 days by people in the network. Generated by `tools/update_papers.py`; edits here are overwritten.',
		'Papers from the last 90 days by people in the network. Generated by the Scientist network plugin; edits here are overwritten.',
	]) assert.ok(isGeneratedLine(line), line);
});
